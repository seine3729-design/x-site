export const MENU_ICON_NAMES = Object.keys(MENU_ICONS).sort()

/** 按名称取图标；名称为空或未登记时返回默认图标。 */
export function resolveIcon(name: string | undefined): LucideIcon {
  return (name && MENU_ICONS[name]) || Circle
}

/** 菜单类型的默认图标：目录、页面、外链没有设置图标时用。 */
const KIND_ICONS: Record<'group' | 'page' | 'link', LucideIcon> = {
  group: Folder,
  page: Circle,
  link: Link,
}

/**
 * 侧栏菜单的图标。一级、二级菜单都必须有图标，否则同级菜单的文字对不齐；
 * 没有设置图标（或图标名未登记）时按菜单类型显示默认图标。
 */
export function menuIcon(kind: 'group' | 'page' | 'link', name: string | undefined): LucideIcon {
  return (name && MENU_ICONS[name]) || KIND_ICONS[kind]
}
